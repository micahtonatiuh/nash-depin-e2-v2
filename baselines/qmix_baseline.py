"""
qmix_baseline.py — QMIX (Rashid et al. 2018)
Nash-DePIN — cooperative baseline for E2.

Core idea:
    Q_tot(s, a) = f_mix( Q_1(o_1,a_1), Q_2(o_2,a_2) ; s )

where f_mix is MONOTONIC in each Q_i:
    dQ_tot / dQ_i >= 0    (monotonicity constraint, Eq. 5 of the paper)

This is enforced by making the mixing-network weights NON-NEGATIVE (absolute
value is applied to the weights produced by the hypernetworks). Training uses
a SHARED team reward.

Why this causes monopolization (high Gini) on mixed-motive tasks:
the monotonicity constraint prevents Q_tot from representing NON-MONOTONIC
payoffs — exactly the structure of task competition, where "I win the task"
and "you win the task" are mutually exclusive. QMIX collapses this into a team
policy that typically assigns tasks to a single agent, raising the Gini.

Reference: Rashid et al., "QMIX: Monotonic Value Function Factorisation for
Deep Multi-Agent Reinforcement Learning", 2018.
"""

import numpy as np
import random
from collections import deque

import torch
import torch.nn as nn
import torch.nn.functional as F


class AgentNet(nn.Module):
    """Per-agent Q network: observation -> Q value per action."""

    def __init__(self, obs_dim, n_actions, hidden=64):
        super().__init__()
        self.fc1 = nn.Linear(obs_dim, hidden)
        self.fc2 = nn.Linear(hidden, hidden)
        self.out = nn.Linear(hidden, n_actions)

    def forward(self, obs):
        x = F.relu(self.fc1(obs))
        x = F.relu(self.fc2(x))
        return self.out(x)


class MixingNetwork(nn.Module):
    """
    QMIX monotonic mixing network.

    Combines Q_1 and Q_2 into Q_tot using weights generated by hypernetworks
    from the global state. Weights are forced non-negative with torch.abs(),
    guaranteeing monotonicity dQ_tot/dQ_i >= 0.
    """

    def __init__(self, n_agents, state_dim, mixing_hidden=32):
        super().__init__()
        self.n_agents = n_agents
        self.mixing_hidden = mixing_hidden

        # Hypernetworks: global state -> mixing network weights
        self.hyper_w1 = nn.Linear(state_dim, n_agents * mixing_hidden)
        self.hyper_w2 = nn.Linear(state_dim, mixing_hidden)
        # Biases (not required to be non-negative)
        self.hyper_b1 = nn.Linear(state_dim, mixing_hidden)
        self.hyper_b2 = nn.Sequential(
            nn.Linear(state_dim, mixing_hidden),
            nn.ReLU(),
            nn.Linear(mixing_hidden, 1),
        )

    def forward(self, agent_qs, state):
        """
        agent_qs: [batch, n_agents]  (each agent's Q for its chosen action)
        state:    [batch, state_dim] (global state)
        Returns:  [batch] Q_tot
        """
        batch = agent_qs.size(0)

        # Layer 1: NON-NEGATIVE weights (abs) -> monotonicity
        w1 = torch.abs(self.hyper_w1(state)).view(batch, self.n_agents, self.mixing_hidden)
        b1 = self.hyper_b1(state).view(batch, 1, self.mixing_hidden)
        agent_qs = agent_qs.view(batch, 1, self.n_agents)
        hidden = F.elu(torch.bmm(agent_qs, w1) + b1)   # [batch, 1, mixing_hidden]

        # Layer 2: NON-NEGATIVE weights (abs) -> monotonicity
        w2 = torch.abs(self.hyper_w2(state)).view(batch, self.mixing_hidden, 1)
        b2 = self.hyper_b2(state).view(batch, 1, 1)
        q_tot = torch.bmm(hidden, w2) + b2             # [batch, 1, 1]
        return q_tot.view(batch)


class QMIXTeam:
    """
    QMIX team: 2 agents + monotonic mixing network.
    Trains on a SHARED team reward (the sum of individual rewards).
    """

    def __init__(self, obs_dim, state_dim, n_actions, cfg, seed=0):
        torch.manual_seed(seed)
        np.random.seed(seed)
        random.seed(seed)

        nn_cfg = cfg["neural"]
        lp = cfg["learning"]
        self.n_actions = n_actions
        self.n_agents = 2
        self.gamma = lp["gamma"]
        self.epsilon = lp["epsilon_start"]
        self.epsilon_min = lp["epsilon_min"]
        self.epsilon_decay = lp["epsilon_decay"]
        self.batch_size = nn_cfg["batch_size"]
        self.target_update = nn_cfg["target_update"]

        # Agent networks
        self.q_nets = [AgentNet(obs_dim, n_actions, nn_cfg["hidden_dim"]) for _ in range(2)]
        self.target_nets = [AgentNet(obs_dim, n_actions, nn_cfg["hidden_dim"]) for _ in range(2)]
        # Mixing network
        self.mixer = MixingNetwork(2, state_dim, nn_cfg["mixing_hidden"])
        self.target_mixer = MixingNetwork(2, state_dim, nn_cfg["mixing_hidden"])

        for i in range(2):
            self.target_nets[i].load_state_dict(self.q_nets[i].state_dict())
        self.target_mixer.load_state_dict(self.mixer.state_dict())

        params = [p for net in self.q_nets for p in net.parameters()]
        params += list(self.mixer.parameters())
        self.optimizer = torch.optim.Adam(params, lr=nn_cfg["lr"])

        self.buffer = deque(maxlen=nn_cfg["buffer_size"])
        self.step_count = 0

    def act(self, state, obs):
        """epsilon-greedy over each agent Q network (decentralized execution)."""
        actions = []
        for i in range(2):
            if random.random() < self.epsilon:
                actions.append(random.randint(0, self.n_actions - 1))
            else:
                with torch.no_grad():
                    q = self.q_nets[i](torch.tensor(obs[i], dtype=torch.float32))
                    actions.append(int(q.argmax().item()))
        return tuple(actions)

    def learn(self, state_vec, actions, rewards, next_state_vec, obs, next_obs, done):
        """
        Trains on the TEAM reward (sum) — QMIX is purely cooperative.
        state_vec / next_state_vec: global state vectors (for the mixer).
        """
        team_reward = float(np.sum(rewards))   # shared reward
        self.buffer.append(
            (obs.copy(), actions, team_reward, next_obs.copy(),
             state_vec.copy(), next_state_vec.copy(), done)
        )
        self.step_count += 1

        if len(self.buffer) < self.batch_size:
            return

        batch = random.sample(self.buffer, self.batch_size)
        obs_b   = torch.tensor(np.array([b[0] for b in batch]), dtype=torch.float32)
        act_b   = torch.tensor(np.array([b[1] for b in batch]), dtype=torch.long)
        rew_b   = torch.tensor(np.array([b[2] for b in batch]), dtype=torch.float32)
        nobs_b  = torch.tensor(np.array([b[3] for b in batch]), dtype=torch.float32)
        st_b    = torch.tensor(np.array([b[4] for b in batch]), dtype=torch.float32)
        nst_b   = torch.tensor(np.array([b[5] for b in batch]), dtype=torch.float32)
        done_b  = torch.tensor(np.array([b[6] for b in batch]), dtype=torch.float32)

        # Q_i for the action taken
        chosen_qs = torch.zeros(self.batch_size, 2)
        for i in range(2):
            q_i = self.q_nets[i](obs_b[:, i, :])
            chosen_qs[:, i] = q_i.gather(1, act_b[:, i:i+1]).squeeze(1)
        q_tot = self.mixer(chosen_qs, st_b)

        # Target computed with the target mixing network
        with torch.no_grad():
            next_qs = torch.zeros(self.batch_size, 2)
            for i in range(2):
                q_next = self.target_nets[i](nobs_b[:, i, :])
                next_qs[:, i] = q_next.max(dim=1)[0]
            q_tot_next = self.target_mixer(next_qs, nst_b)
            target = rew_b + self.gamma * q_tot_next * (1 - done_b)

        loss = F.mse_loss(q_tot, target)
        self.optimizer.zero_grad()
        loss.backward()
        self.optimizer.step()

        if self.step_count % self.target_update == 0:
            for i in range(2):
                self.target_nets[i].load_state_dict(self.q_nets[i].state_dict())
            self.target_mixer.load_state_dict(self.mixer.state_dict())

    def end_episode(self):
        self.epsilon = max(self.epsilon_min, self.epsilon * self.epsilon_decay)
